/*
  Цей скрипт імітує повний процес "Оформлення замовлення"
  і об'єднаний в одну транзакцію, щоб гарантувати
  цілісність даних (принцип "все або нічого").
*/

-- 1. Вибираємо нашу базу даних для роботи
USE plants;

-- 2. КОНТРОЛЬНА ТОЧКА "ДО"
-- Давайте подивимося на кількість товарів (quantity) 
-- *перед* тим, як ми почнемо транзакцію.
-- (Припускаємо, що товари з id 1 та 2 і клієнт з id 1 існують)
SELECT * FROM Product WHERE id IN (1, 2);

-- 3. ПОЧАТОК ТРАНЗАКЦІЇ
-- З цієї миті, всі операції є частиною єдиного цілого.
-- Вони або всі будуть застосовані (COMMIT), 
-- або всі будуть скасовані (ROLLBACK) у разі помилки.
START TRANSACTION;

-- КРОК 1: Створюємо саме замовлення (порожній "кошик")
-- Вставляємо новий рядок в `Order` для клієнта з id=1.
INSERT INTO `Order` (status, clientId) 
VALUES ('Pending', 1);

-- КРОК 2: Отримуємо ID щойно створеного замовлення
-- @order_id -- це змінна, яка буде жити протягом цього сеансу.
-- LAST_INSERT_ID() -- це функція MySQL, що повертає
-- останній згенерований AUTO_INCREMENT id.
SET @order_id = LAST_INSERT_ID();

-- КРОК 3: Додаємо перший товар (id=1) у замовлення
-- Спочатку отримуємо та фіксуємо його ціну НА МОМЕНТ ПОКУПКИ
SELECT price INTO @p1_price FROM Product WHERE id = 1;

-- Тепер вставляємо рядок у вміст замовлення:
-- Товар 1, 2 штуки, за зафіксованою ціною @p1_price
INSERT INTO OrderContent (orderId, productId, productPrice, productQuantity)
VALUES (@order_id, 1, @p1_price, 2);

-- КРОК 4: Оновлюємо (зменшуємо) залишки товару 1 на складі
-- Це критично важливий крок. 
-- Якщо тут (або десь нижче) станеться помилка 
-- (напр., товару на складі менше, ніж 2), вся транзакція "відкотиться".
UPDATE Product 
SET quantity = quantity - 2 
WHERE id = 1;

-- КРОК 5: Додаємо другий товар (id=2) у замовлення
-- Повторюємо логіку: отримуємо ціну...
SELECT price INTO @p2_price FROM Product WHERE id = 2;

-- ...і додаємо товар у вміст замовлення:
-- Товар 2, 1 штука, за зафіксованою ціною @p2_price
INSERT INTO OrderContent (orderId, productId, productPrice, productQuantity)
VALUES (@order_id, 2, @p2_price, 1);

-- КРОК 6: Оновлюємо (зменшуємо) залишки товару 2 на складі
UPDATE Product 
SET quantity = quantity - 1 
WHERE id = 2;

-- КРОК 7: ФІКСАЦІЯ ТРАНЗАКЦІЇ
-- Якщо ми дійшли до цього моменту без помилок,
-- команда COMMIT "зберігає" всі наші зміни (INSERTs та UPDATEs)
-- в базі даних. Тільки тепер вони стануть видимими 
-- для інших користувачів.
COMMIT;

-- 4. КОНТРОЛЬНА ТОЧКА "ПІСЛЯ"
-- Тепер, коли транзакція завершена, давайте подивимося на результат.

-- 4.1. Перевіряємо залишки на складі:
SELECT '--- Залишки на складі (ПІСЛЯ) ---' AS check_point;
SELECT * FROM Product WHERE id IN (1, 2); -- Кількість (quantity) має зменшитись

-- 4.2. Перевіряємо, чи створено наше замовлення:
SELECT '--- Нове замовлення (ПІСЛЯ) ---' AS check_point;
SELECT * FROM `Order` WHERE id = @order_id; -- Маємо побачити 1 рядок з нашим @order_id

-- 4.3. Перевіряємо вміст нашого замовлення:
SELECT '--- Вміст замовлення (ПІСЛЯ) ---' AS check_point;
SELECT * FROM OrderContent WHERE orderId = @order_id; -- Маємо побачити 2 рядки (для товару 1 і 2)
